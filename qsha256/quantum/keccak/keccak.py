"""Keccak-f[1600]: classical reference and reversible quantum circuit.

State layout follows the standard: a 5x5 array of 64-bit lanes, indexed
``A[x][y]``, with lane bit ``z`` being bit ``z`` of the lane.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from ..registers import CircuitBuilder, Word
from ..strategies import DEFAULT, Strategy

