@dataclass
class KeccakCircuit:
    builder: CircuitBuilder
    #: The lane holding the state on input, ``[x][y]``.
    state: list[list[Word]]
    #: The lane holding the state on output (ping-pong may swap the registers).
    output: list[list[Word]]
    rounds: int = ROUNDS
    scratch: list[list[Word]] = field(default_factory=list)
    #: theta's per-round scratch lanes, which this construction does not clear.
    theta_garbage: list[Word] = field(default_factory=list)

    @property
    def circuit(self):
        return self.builder.circuit


def _theta_inplace(b: CircuitBuilder, a: list[list[Word]], rnd: int) -> list[Word]:
    """Apply ``theta`` in place, returning the scratch lanes it could not clear.

    ``D[x] = C[x-1] XOR ROTL(C[x+1], 1)`` where ``C[x]`` is column ``x``'s
    parity.  Computing it is easy; *un*computing it is not, and the reason is
    worth recording because it is a genuine structural obstacle rather than an
    oversight.

    After the fold, column ``x`` has gained ``D[x]`` in all five of its lanes.
    Five is odd, so the column's parity changed by exactly ``D[x]``.  Recovering
    the original parities therefore needs ``D`` -- which is what we are trying to
    erase.  Writing the dependency out gives ``(I + M) D = v`` over GF(2), whose
    solution requires inverting a linear map on the whole 1600-bit state.  Every
    ordering of the obvious local moves runs into the same cycle, because
    ``D[x]`` depends on ``D[x-1]`` and ``D[x+1]`` around a 5-cycle.

    So this implementation **keeps** the scratch: 5 lanes (320 qubits) per round,
    7,680 qubits across the permutation.  That is the honest cost of the simple
    construction.  Closing it needs in-place CNOT-only synthesis of theta as an
    invertible GF(2) map -- which is what Amy et al. do, and it is why their
    circuit fits in 3,200 qubits while paying ~33 million CNOTs for the privilege.
    The tradeoff is recorded in the resource report rather than hidden.
    """
    from ..primitives.xor import xor_word

    def rotl1(word: Word) -> Word:
        return Word(word.bits[-1:] + word.bits[:-1], f"rotl1({word.label})")

    with b.section("theta"):
        d = [b.add_word(LANE_BITS, f"D{rnd}_{x}") for x in range(LANES)]
        for x in range(LANES):
            left, right = (x - 1) % LANES, (x + 1) % LANES
            for y in range(LANES):
                xor_word(b, a[left][y], d[x])
            for y in range(LANES):
                xor_word(b, rotl1(a[right][y]), d[x])
        for x in range(LANES):
            for y in range(LANES):
                xor_word(b, d[x], a[x][y])
    return d


def _rho_pi(a: list[list[Word]]) -> list[list[Word]]:
    """rho and pi together: pure rewiring, zero gates."""
    b: list[list[Word | None]] = [[None] * LANES for _ in range(LANES)]
    for x in range(LANES):
        for y in range(LANES):
            offset = KECCAK_ROTATION_OFFSETS[x][y] % LANE_BITS
            lane = a[x][y]
            # ROTL by `offset` on an LSB-first word.
            rotated = Word(
                lane.bits[-offset:] + lane.bits[:-offset] if offset else lane.bits,
                f"rho({lane.label})",
            )
            b[y][(2 * x + 3 * y) % LANES] = rotated
    return b  # type: ignore[return-value]


def _chi_into(
    b: CircuitBuilder, src: list[list[Word]], dst: list[list[Word]], use_gidney: bool
) -> None:
    """``dst = chi(src)`` with ``dst`` starting in ``|0>``.  One AND per bit."""
    from ..primitives.xor import xor_word

    with b.section("chi"):
        for y in range(LANES):
            for x in range(LANES):
                target = dst[x][y]
                xor_word(b, src[x][y], target)
                n1 = src[(x + 1) % LANES][y]
                n2 = src[(x + 2) % LANES][y]
                for z in range(LANE_BITS):
                    b.x(n1[z])
                    b.ccx(n1[z], n2[z], target[z])
                    b.x(n1[z])


def _chi_inverse_clear(
    b: CircuitBuilder, dst: list[list[Word]], src: list[list[Word]], use_gidney: bool
) -> None:
    """Clear ``src`` given ``dst = chi(src)``, using ``chi^-1``.

    ``chi^-1`` is two ANDs deep, which is the structural reason a reversible
    Keccak round costs roughly three times its forward AND count.
    """
    from ..primitives.xor import xor_word

    with b.section("chi inverse (clear source)"):
        for y in range(LANES):
            for x in range(LANES):
                target = src[x][y]
                b1 = dst[(x + 1) % LANES][y]
                b2 = dst[(x + 2) % LANES][y]
                b3 = dst[(x + 3) % LANES][y]
                b4 = dst[(x + 4) % LANES][y]
                with b.ancillas.borrow(LANE_BITS, "chi_inv_u") as u:
                    # u = B[x+2] XOR (NOT B[x+3] AND B[x+4])
                    # u starts |0>, so its AND may use Gidney's construction;
                    # the state lane below may not, since it is not clean.
                    for z in range(LANE_BITS):
                        b.x(b3[z])
                        if use_gidney:
                            b.and_g(b3[z], b4[z], u[z])
                        else:
                            b.ccx(b3[z], b4[z], u[z])
                        b.x(b3[z])
                    xor_word(b, b2, u)
                    # A[x] ^= B[x] XOR (NOT B[x+1] AND u)  ->  A[x] becomes 0
                    xor_word(b, dst[x][y], target)
                    for z in range(LANE_BITS):
                        b.x(b1[z])
                        b.ccx(b1[z], u[z], target[z])
                        b.x(b1[z])
                    # uncompute u: free under Gidney, since it is a
                    # measurement plus a Clifford correction.
                    xor_word(b, b2, u)
                    for z in range(LANE_BITS):
                        b.x(b3[z])
                        if use_gidney:
                            b.and_g_dg(b3[z], b4[z], u[z])
                        else:
                            b.ccx(b3[z], b4[z], u[z])
                        b.x(b3[z])


def _iota(b: CircuitBuilder, a: list[list[Word]], rnd: int) -> None:
    from ..primitives.xor import xor_const

    with b.section("iota"):
        xor_const(b, KECCAK_ROUND_CONSTANTS[rnd], a[0][0])


def build_keccak_f(
    rounds: int = ROUNDS,
    strategy: Strategy = DEFAULT,
    builder: CircuitBuilder | None = None,
    state: list[list[Word]] | None = None,
) -> KeccakCircuit:
    """Build a reversible Keccak-f[1600] over ``rounds`` rounds.

    Uses two 1600-qubit registers, ping-ponging: ``chi`` writes into the spare
    and ``chi^-1`` clears the source, so the spare becomes the state and the
    old state becomes the spare.  The swap itself is free -- it is a relabelling.
    """
    b = builder or CircuitBuilder(f"keccak_f_r{rounds}")
    if state is None:
        state = [[b.add_word(LANE_BITS, f"A{x}{y}") for y in range(LANES)] for x in range(LANES)]
    spare = [[b.add_word(LANE_BITS, f"B{x}{y}") for y in range(LANES)] for x in range(LANES)]

    current, other = state, spare
    garbage: list[Word] = []
    use_gidney = strategy.adder == "gidney"

    for rnd in range(rounds):
        with b.section(f"round[{rnd}]"):
            garbage.extend(_theta_inplace(b, current, rnd))
            permuted = _rho_pi(current)
            _chi_into(b, permuted, other, use_gidney)
            _chi_inverse_clear(b, other, permuted, use_gidney)
            _iota(b, other, rnd)
        current, other = other, current

    return KeccakCircuit(
        builder=b,
        state=state,
        output=current,
        rounds=rounds,
        scratch=other,
        theta_garbage=garbage,
    )


def build_sha3(rounds: int = ROUNDS, strategy: Strategy = DEFAULT) -> KeccakCircuit:
    """A single Keccak-f permutation, which is the whole cost of a SHA3 block."""
    return build_keccak_f(rounds, strategy)
