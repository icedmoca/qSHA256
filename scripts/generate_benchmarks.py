#!/usr/bin/env python3
"""Regenerate every published benchmark table in this repository.

    python scripts/generate_benchmarks.py

Writes to ``benchmarks/results/``:

    latest.json        every report, in full, with environment metadata
    latest.csv         the same rows, flat, for diffing between commits
    latest.md          the Markdown tables the README and docs quote

Nothing in the README is typed by hand.  If a number there disagrees with what
this script produces, the README is wrong.
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from qsha256 import SHA256  # noqa: E402
from qsha256.quantum.optimization.hardware import rank_for_hardware  # noqa: E402
from qsha256.quantum.oracle.grover import grover_cost_estimate  # noqa: E402
from qsha256.quantum.oracle.preimage import build_preimage_oracle  # noqa: E402
from qsha256.quantum.resources import analyze, estimate_physical  # noqa: E402
from qsha256.quantum.resources.analyzer import environment_metadata  # noqa: E402
from qsha256.quantum.resources.leaderboard import build_leaderboard  # noqa: E402
from qsha256.quantum.resources.reports import to_csv, to_markdown  # noqa: E402
from qsha256.quantum.sha256.compression import build_compression  # noqa: E402
from qsha256.quantum.strategies import Strategy  # noqa: E402
from qsha256.validation.benchmark import run_scaling_benchmark, run_strategy_benchmark  # noqa: E402

OUT = ROOT / "benchmarks" / "results"
ROUNDS = (1, 2, 4, 8, 16, 32, 64)

#: Architectures compared at full 64 rounds.
STRATEGIES = [
    Strategy(),
    Strategy(const_add="vbe_const"),
    Strategy(schedule="store_all"),
    Strategy(round_layout="wide"),
    Strategy(round_layout="csa"),
    Strategy(adder="vbe"),
    Strategy(adder="qft"),
    Strategy(adder="gidney"),
    Strategy(uncompute_working=True),
    Strategy(adder="gidney", uncompute_working=True),
]

#: Post-construction optimizations, applied to the default and Gidney designs.
OPTIMIZED = [
    (Strategy(), True, "cdkm + phase folding"),
    (Strategy(adder="gidney"), False, "gidney temporary ANDs"),
    (Strategy(adder="gidney"), True, "gidney + phase folding"),
]


def log(message: str) -> None:
    print(f"[{time.strftime('%H:%M:%S')}] {message}", file=sys.stderr, flush=True)


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    started = time.time()
    payload: dict = {"environment": environment_metadata(), "tables": {}}
    markdown: list[str] = [
        "# qSHA256 benchmark results",
        "",
        "Generated by `python scripts/generate_benchmarks.py`. Do not edit by hand.",
        "",
        f"- qSHA256 {payload['environment']['qsha256_version']}",
        f"- Qiskit {payload['environment']['qiskit_version']}",
        f"- Python {payload['environment']['python_version']}",
        f"- generated {payload['environment']['timestamp']}",
        "",
        "All gate counts, depths and qubit counts are **measured** from constructed",
        "circuits. T-counts and T-depths marked `TRAN` are measured from a circuit",
        "actually transpiled into the Clifford+T basis; `ANAL` means the measured",
        "Toffoli count was multiplied by the standard 7-T decomposition instead.",
        "",
    ]

    # -- 1. scaling with rounds ------------------------------------------
    log("scaling benchmark: SHA-256 forward compression, 1..64 rounds")
    scaling = run_scaling_benchmark(SHA256, ROUNDS, Strategy(), progress=log)
    payload["tables"]["scaling_forward"] = [r.to_dict() for r in scaling]
    markdown += [
        "## Scaling with round count",
        "",
        "Default architecture (CDKM adder, rolling schedule, serial round layout),",
        "forward evaluation only. Each row is built and measured independently.",
        "",
        to_markdown(scaling),
        "",
        "The cost is not linear in rounds: the message schedule does not begin",
        "expanding until round 16, because rounds 0-15 consume the message block",
        "directly.",
        "",
    ]

    # -- 2. scaling, garbage-free ----------------------------------------
    log("scaling benchmark: garbage-free (oracle-ready)")
    scaling_gf = run_scaling_benchmark(
        SHA256, ROUNDS, Strategy(uncompute_working=True), progress=log
    )
    payload["tables"]["scaling_garbage_free"] = [r.to_dict() for r in scaling_gf]
    markdown += [
        "## Scaling, garbage-free",
        "",
        "The same architecture with uncomputation enabled, so work registers, the",
        "message schedule and the message block are all restored. This is the form",
        "a Grover oracle needs.",
        "",
        to_markdown(scaling_gf),
        "",
    ]

    # -- 3. architecture comparison --------------------------------------
    log("architecture comparison at 64 rounds")
    designs = run_strategy_benchmark(SHA256, STRATEGIES, rounds=64, progress=log)
    payload["tables"]["architectures"] = [r.to_dict() for r in designs]
    markdown += [
        "## Architecture comparison, 64 rounds",
        "",
        to_markdown(designs),
        "",
        "Read this table carefully. The QFT adder has by far the fewest Toffoli",
        "gates -- and by far the worst T-count, because its arbitrary-angle",
        "rotations must be synthesised from Clifford+T at a cost far exceeding the",
        "Toffolis they replaced. A Toffoli count is not a fault-tolerant cost.",
        "",
    ]

    # -- 3b. post-construction optimization -------------------------------
    log("post-construction optimization (phase folding, temporary ANDs)")
    from qsha256.quantum.optimization.rewrite import apply_rewrites

    baseline_design = designs[0]
    optimized_reports = [baseline_design]
    opt_rows = [
        "## Post-construction optimization, 64 rounds",
        "",
        "Two optimizations that operate below the architectural level:",
        "**Gidney temporary ANDs** replace every adder Toffoli with a 4-T compute",
        "and a measurement-based, T-free uncomputation; **phase folding** merges",
        "T gates acting on the same GF(2) linear function (the core of T-par).",
        "",
        "| Design | Qubits | Toffoli | and_g | T-count | vs base "
        "| Non-Clifford depth | Measurements |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]

    def _opt_row(label, report):
        ct = report.clifford_t
        delta = 100 * (ct["t_count"] / baseline_design.t_count - 1)
        opt_rows.append(
            f"| {label} | {report.width:,} | {report.toffoli_count:,} | "
            f"{ct.get('and_compute_gates', 0):,} | {ct['t_count']:,} | {delta:+.1f}% | "
            f"{report.depth['non_clifford_depth']:,} | {ct['measurements']:,} |"
        )

    _opt_row("cdkm (baseline)", baseline_design)
    for strategy, fold, label in OPTIMIZED:
        log(f"  {label}")
        comp = build_compression(SHA256, strategy, rounds=64)
        if fold:
            optimized = apply_rewrites(comp.builder, phase_folding=True)
            report = analyze(
                optimized.circuit,
                spec=SHA256,
                strategy=strategy,
                rounds=64,
                target=label,
                transpile_t=False,
            )
            report.width = comp.circuit.num_qubits
        else:
            report = analyze(
                comp,
                spec=SHA256,
                strategy=strategy,
                rounds=64,
                target=label,
                transpile_t=False,
            )
        optimized_reports.append(report)
        _opt_row(label, report)

    payload["tables"]["optimized"] = [r.to_dict() for r in optimized_reports]
    best = min(optimized_reports, key=lambda r: r.t_count)
    opt_rows += [
        "",
        f"Lowest T-count found: **{best.t_count:,}** ({best.target}).",
        "",
        "Read the depth column alongside the T-count. Phase folding cuts T-count",
        "substantially but *raises* non-Clifford depth, because merging phases onto",
        "the first point where each linear function is live serialises them. The",
        "Gidney adder improves both at once, at the cost of requiring mid-circuit",
        "measurement and classical feedforward -- a hardware assumption the other",
        "designs do not make.",
        "",
    ]
    markdown += opt_rows

    # -- 4. component breakdown ------------------------------------------
    log("component cost breakdown")
    full = scaling[-1]
    total = max(1, full.toffoli_count)
    rows = sorted(full.component_costs.items(), key=lambda kv: -kv[1].get("_ccx", 0))
    payload["tables"]["components"] = full.component_costs
    markdown += [
        "## Where the cost goes (64 rounds, forward)",
        "",
        "| Component | Gates | Toffoli | % of Toffoli |",
        "|---|---:|---:|---:|",
    ]
    for name, data in rows:
        markdown.append(
            f"| {name} | {data.get('_total', 0):,} | {data.get('_ccx', 0):,} | "
            f"{100 * data.get('_ccx', 0) / total:.1f}% |"
        )
    markdown += [
        "",
        "Components are disjoint and sum exactly to the circuit total.",
        "",
    ]

    # -- 5. preimage oracle ----------------------------------------------
    log("building the full SHA-256 preimage oracle")
    oracle = build_preimage_oracle(
        SHA256,
        Strategy(uncompute_working=True),
        rounds=64,
        target_digest=0,
        initial_state=tuple(SHA256.h0),
    )
    oracle_report = analyze(
        oracle.builder,
        spec=SHA256,
        strategy=oracle.strategy,
        rounds=64,
        target="SHA-256 preimage oracle",
        transpile_t=True,
        reproduce="qsha256 oracle --rounds 64",
    )
    payload["tables"]["oracle"] = oracle_report.to_dict()
    markdown += [
        "## SHA-256 preimage oracle",
        "",
        "Forward hash, digest comparison against a target, phase flip, inverse hash.",
        "",
        to_markdown([oracle_report]),
        "",
        f"- Oracle Toffoli count: {oracle_report.toffoli_count:,}",
        f"- Forward-only compression Toffoli count: {scaling[-1].toffoli_count:,}",
        f"- Ratio: {oracle_report.toffoli_count / max(1, scaling[-1].toffoli_count):.2f}x",
        "",
        "One Grover query is not one SHA-256 evaluation.",
        "",
    ]

    # -- 6. Grover extrapolation -----------------------------------------
    grover = grover_cost_estimate(oracle_report, search_bits=256)
    payload["tables"]["grover"] = grover.to_dict()
    markdown += [
        "## Grover preimage extrapolation",
        "",
        "```",
        str(grover),
        "```",
        "",
    ]

    # -- 7. physical estimates -------------------------------------------
    log("fault-tolerant estimates")
    physical = {}
    markdown += [
        "## Fault-tolerant estimates for one oracle call",
        "",
        "**Assumption-dependent.** These change with the hardware model; see",
        "`qsha256/quantum/resources/physical.py` for every formula and parameter.",
        "",
        "| Model | Code distance | Physical qubits | Runtime (one oracle call) |",
        "|---|---:|---:|---:|",
    ]
    for model in ("optimistic", "superconducting", "conservative"):
        estimate = estimate_physical(oracle_report, model)
        physical[model] = estimate.to_dict()
        if estimate.achievable:
            markdown.append(
                f"| {model} | {estimate.code_distance} | "
                f"{estimate.physical_qubits_total:,} | {estimate.runtime_seconds:,.3g} s |"
            )
        else:
            markdown.append(f"| {model} | - | not achievable | - |")
    payload["tables"]["physical"] = physical
    markdown.append("")

    # -- 8. hardware-aware ranking ---------------------------------------
    log("hardware-aware ranking")

    class _Point:
        def __init__(self, label, report):
            self.label, self.report = label, report

    points = [_Point(r.strategy.get("label", "?"), r) for r in designs]
    markdown += ["## Hardware-aware ranking", "", ""]
    hardware = {}
    for model in ("superconducting", "optimistic"):
        ranking = rank_for_hardware(points, model)
        hardware[model] = ranking.to_dict()
        markdown += [
            f"### {model}",
            "",
            "| Design | d | Physical qubits | Runtime | Qubit-seconds |",
            "|---|---:|---:|---:|---:|",
        ]
        for scored in sorted(ranking.scored, key=lambda s: s.spacetime_volume):
            est = scored.estimate
            if not est.achievable:
                markdown.append(f"| {scored.label} | - | not achievable | - | - |")
                continue
            markdown.append(
                f"| {scored.label} | {est.code_distance} | "
                f"{est.physical_qubits_total:,} | {est.runtime_seconds:,.3g} s | "
                f"{scored.spacetime_volume:.3g} |"
            )
        markdown += ["", f"Best for this machine: **{ranking.best.label}**", ""]
    payload["tables"]["hardware_ranking"] = hardware

    # -- 9. leaderboard ---------------------------------------------------
    log("leaderboard against published circuits")
    leaderboard = {}
    markdown += [
        "## Comparison with published circuits",
        "",
        "Compared below is the *default* forward compression circuit. The"
        " optimized designs are summarised after the tables.",
        "",
    ]
    for key in ("amy2016", "amy2016-opt"):
        rows = build_leaderboard(full, key)
        leaderboard[key] = [
            {
                "metric": r.metric,
                "qsha256": r.ours,
                "published": r.theirs,
                "ratio": r.ratio,
                "comparability": r.comparability,
                "verdict": r.verdict,
            }
            for r in rows
        ]
        from qsha256.quantum.resources.leaderboard import PUBLISHED

        markdown += [
            f"### vs {PUBLISHED[key].label}",
            "",
            f"Source: {PUBLISHED[key].source}",
            "",
            "| Metric | qSHA256 | Published | Ratio | Verdict |",
            "|---|---:|---:|---:|---|",
        ]
        for r in rows:
            ours = f"{r.ours:,}" if r.ours is not None else "-"
            theirs = f"{r.theirs:,}" if r.theirs is not None else "not reported"
            ratio = f"{r.ratio:.2f}x" if r.ratio is not None else "-"
            flag = "" if r.comparability == "DIRECT" else f" ({r.comparability.lower()})"
            markdown.append(f"| {r.metric} | {ours} | {theirs} | {ratio} | {r.verdict}{flag} |")
        markdown.append("")
    payload["tables"]["leaderboard"] = leaderboard

    # How the optimized designs land against the published T-counts.
    published_t = PUBLISHED["amy2016-opt"].t_count
    markdown += [
        "### Optimized designs versus the published T-par result",
        "",
        f"Amy et al. report **{published_t:,} T** after T-par optimization,"
        f" at 2,402 logical qubits.",
        "",
        "| qSHA256 design | Qubits | T-count | vs published | Same machine model? |",
        "|---|---:|---:|---:|---|",
    ]
    for report in optimized_reports:
        delta = 100 * (report.t_count / published_t - 1)
        ff = report.clifford_t.get("needs_feedforward")
        model = "no - needs measurement + feedforward" if ff else "yes - unitary Clifford+T"
        markdown.append(
            f"| {report.target} | {report.width:,} | {report.t_count:,} | {delta:+.1f}% | {model} |"
        )
    markdown += [
        "",
        "The like-for-like comparison is the unitary row: phase folding alone"
        " reaches a lower T-count than the published T-par result at under half"
        " the qubits. The Gidney rows go further still, but assume a capability"
        " the 2016 circuit did not -- see the caveat in `docs/leaderboard.md`.",
        "",
    ]

    payload["elapsed_seconds"] = round(time.time() - started, 1)
    markdown += [
        "---",
        "",
        f"Total generation time: {payload['elapsed_seconds']:.0f}s.",
        "",
        "No circuit in this repository has ever been executed on quantum hardware.",
    ]

    (OUT / "latest.json").write_text(json.dumps(payload, indent=2, default=str))
    (OUT / "latest.csv").write_text(to_csv(scaling + scaling_gf + designs + [oracle_report]))
    (OUT / "latest.md").write_text("\n".join(markdown) + "\n")

    log(f"wrote {OUT}/latest.{{json,csv,md}} in {payload['elapsed_seconds']:.0f}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
